using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;

namespace Enbrea.Bcp47.Iana.SourceGenerator;

/// <summary>
/// Builds the C# source containing the compact IANA registry data used at runtime.
/// </summary>
internal static class RegistrySourceBuilder
{
    private static readonly StringComparer Comparer = StringComparer.OrdinalIgnoreCase;

    /// <summary>
    /// Builds the C# source containing the compact IANA registry data used at runtime.
    /// </summary>
    /// <param name="snapshot">The registry snapshot to build the source from.</param>
    /// <returns>The generated C# source code as a string.</returns>
    public static string Build(RegistrySnapshot snapshot)
    {
        if (snapshot is null)
        {
            throw new ArgumentNullException(nameof(snapshot));
        }

        if (!DateTime.TryParseExact(snapshot.FileDate, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var fileDate))
        {
            throw new InvalidOperationException("The registry snapshot does not contain a valid 'fileDate' in yyyy-MM-dd format.");
        }

        if (snapshot.Records is null)
        {
            throw new InvalidOperationException("The registry snapshot does not contain a 'records' array.");
        }

        ValidateRecords(snapshot.Records);

        var source = new StringBuilder(220_000);

        source.AppendLine("// <auto-generated />");
        source.AppendLine("//");
        source.AppendLine("// Generated from the IANA Language Subtag Registry.");
        source.AppendLine($"// Registry file date: {snapshot.FileDate}.");
        source.AppendLine("// Do not edit this file by hand.");
        source.AppendLine("// Exact-value arrays are sorted with StringComparer.OrdinalIgnoreCase.");
        source.AppendLine("// Registry ranges such as qaa..qtz are represented separately as RegistryRangeEntry values.");
        source.AppendLine();
        source.AppendLine("namespace Enbrea.Bcp47.Iana;");
        source.AppendLine();
        source.AppendLine("public static partial class IanaLanguageSubtagRegistry");
        source.AppendLine("{");
        source.AppendLine($"    public static readonly global::System.DateOnly FileDate = new({fileDate.Year}, {fileDate.Month}, {fileDate.Day});");
        source.AppendLine();

        AppendRegistryType(source, snapshot.Records, "language", "Languages", "LanguageRanges");
        AppendRegistryType(source, snapshot.Records, "extlang", "Extlangs", "ExtlangRanges");
        AppendRegistryType(source, snapshot.Records, "script", "Scripts", "ScriptRanges");
        AppendRegistryType(source, snapshot.Records, "region", "Regions", "RegionRanges");
        AppendRegistryType(source, snapshot.Records, "variant", "Variants", "VariantRanges");

        AppendStringArray(source, "GrandfatheredTags", GetExactValues(snapshot.Records, "grandfathered"));
        AppendStringArray(source, "RedundantTags", GetExactValues(snapshot.Records, "redundant"));

        AppendDeprecatedType(source, snapshot.Records, "language", "DeprecatedLanguages", "DeprecatedLanguageRanges");
        AppendDeprecatedType(source, snapshot.Records, "extlang", "DeprecatedExtlangs", "DeprecatedExtlangRanges");
        AppendDeprecatedType(source, snapshot.Records, "script", "DeprecatedScripts", "DeprecatedScriptRanges");
        AppendDeprecatedType(source, snapshot.Records, "region", "DeprecatedRegions", "DeprecatedRegionRanges");
        AppendDeprecatedType(source, snapshot.Records, "variant", "DeprecatedVariants", "DeprecatedVariantRanges");

        AppendStringArray(source, "DeprecatedGrandfatheredTags", GetDeprecatedExactValues(snapshot.Records, "grandfathered"));
        AppendStringArray(source, "DeprecatedRedundantTags", GetDeprecatedExactValues(snapshot.Records, "redundant"));

        AppendValueArray(source, "LanguagePreferredValues", GetValueEntries(snapshot.Records, "language", static record => record.PreferredValue));
        AppendValueArray(source, "ExtlangPreferredValues", GetValueEntries(snapshot.Records, "extlang", static record => record.PreferredValue));
        AppendValueArray(source, "ScriptPreferredValues", GetValueEntries(snapshot.Records, "script", static record => record.PreferredValue));
        AppendValueArray(source, "RegionPreferredValues", GetValueEntries(snapshot.Records, "region", static record => record.PreferredValue));
        AppendValueArray(source, "VariantPreferredValues", GetValueEntries(snapshot.Records, "variant", static record => record.PreferredValue));
        AppendValueArray(source, "GrandfatheredPreferredValues", GetValueEntries(snapshot.Records, "grandfathered", static record => record.PreferredValue));
        AppendValueArray(source, "RedundantPreferredValues", GetValueEntries(snapshot.Records, "redundant", static record => record.PreferredValue));

        AppendValueArray(source, "LanguageSuppressScripts", GetValueEntries(snapshot.Records, "language", static record => record.SuppressScript));
        AppendValueArray(source, "ExtlangSuppressScripts", GetValueEntries(snapshot.Records, "extlang", static record => record.SuppressScript));

        AppendValueArray(source, "LanguageMacrolanguages", GetValueEntries(snapshot.Records, "language", static record => record.Macrolanguage));
        AppendValueArray(source, "ExtlangMacrolanguages", GetValueEntries(snapshot.Records, "extlang", static record => record.Macrolanguage));

        AppendValueArray(source, "ExtlangPrefixes", GetPrefixValueEntries(snapshot.Records, "extlang"));
        AppendPrefixArray(source, "VariantPrefixes", GetPrefixEntries(snapshot.Records, "variant"));

        source.AppendLine("}");

        return source.ToString();
    }

    private static void AppendDeprecatedType(StringBuilder source, IReadOnlyList<RegistryRecord> records, string type, string exactArrayName, string rangeArrayName)
    {
        AppendStringArray(source, exactArrayName, GetDeprecatedExactValues(records, type));
        AppendRangeArray(source, rangeArrayName, GetRanges(records, type, deprecatedOnly: true));
    }

    private static void AppendPrefixArray(StringBuilder source, string name, IReadOnlyList<PrefixEntry> values)
    {
        if (values.Count == 0)
        {
            source.AppendLine($"    internal static readonly RegistryPrefixEntry[] {name} = [];");
            source.AppendLine();
            return;
        }

        source.AppendLine($"    internal static readonly RegistryPrefixEntry[] {name} =");
        source.AppendLine("    [");

        for (var i = 0; i < values.Count; i++)
        {
            source.Append($"        new(\"{Escape(values[i].Subtag)}\", \"{Escape(values[i].Prefix)}\")");
            source.AppendLine(i + 1 < values.Count ? "," : string.Empty);
        }

        source.AppendLine("    ];");
        source.AppendLine();
    }

    private static void AppendRangeArray(StringBuilder source, string name, IReadOnlyList<RangeEntry> values)
    {
        if (values.Count == 0)
        {
            source.Append("    internal static readonly RegistryRangeEntry[] ").Append(name).AppendLine(" = [];");
            source.AppendLine();
            return;
        }

        source.AppendLine($"    internal static readonly RegistryRangeEntry[] {name} =");
        source.AppendLine("    [");

        for (var i = 0; i < values.Count; i++)
        {
            source.Append($"        new(\"{Escape(values[i].Start)}\", \"{Escape(values[i].End)}\")");
            source.AppendLine(i + 1 < values.Count ? "," : string.Empty);
        }

        source.AppendLine("    ];");
        source.AppendLine();
    }

    private static void AppendRegistryType(
        StringBuilder source,
        IReadOnlyList<RegistryRecord> records,
        string type,
        string exactArrayName,
        string rangeArrayName)
    {
        AppendStringArray(source, exactArrayName, GetExactValues(records, type));
        AppendRangeArray(source, rangeArrayName, GetRanges(records, type, deprecatedOnly: false));
    }

    private static void AppendStringArray(StringBuilder source, string name, IReadOnlyList<string> values)
    {
        if (values.Count == 0)
        {
            source.AppendLine($"    internal static readonly string[] {name} = [];");
            source.AppendLine();
            return;
        }

        source.AppendLine($"    internal static readonly string[] {name} =");
        source.AppendLine("    [");

        for (var i = 0; i < values.Count; i++)
        {
            source.Append($"        \"{Escape(values[i])}\"");
            source.AppendLine(i + 1 < values.Count ? "," : string.Empty);
        }

        source.AppendLine("    ];");
        source.AppendLine();
    }

    private static void AppendValueArray(StringBuilder source, string name, IReadOnlyList<ValueEntry> values)
    {
        if (values.Count == 0)
        {
            source.AppendLine($"    internal static readonly RegistryValueEntry[] {name} = [];");
            source.AppendLine();
            return;
        }

        source.AppendLine($"    internal static readonly RegistryValueEntry[] {name} =");
        source.AppendLine("    [");

        for (var i = 0; i < values.Count; i++)
        {
            source.Append($"        new(\"{Escape(values[i].Key)}\", \"{Escape(values[i].Value!)}\")");
            source.AppendLine(i + 1 < values.Count ? "," : string.Empty);
        }

        source.AppendLine("    ];");
        source.AppendLine();
    }

    private static string Escape(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }

    private static IReadOnlyList<string> GetDeprecatedExactValues(IReadOnlyList<RegistryRecord> records, string type)
    {
        return [.. records
            .Where(record => IsType(record, type) && record.Deprecated is not null && !IsRange(record))
            .Select(GetRequiredKey)
            .OrderBy(static value => value, Comparer)];
    }

    private static IReadOnlyList<string> GetExactValues(IReadOnlyList<RegistryRecord> records, string type)
    {
        return [.. records
            .Where(record => IsType(record, type) && !IsRange(record))
            .Select(GetRequiredKey)
            .OrderBy(static value => value, Comparer)];
    }

    private static IReadOnlyList<PrefixEntry> GetPrefixEntries(IReadOnlyList<RegistryRecord> records, string type)
    {
        return [.. records
            .Where(record => IsType(record, type) && record.Prefixes is not null)
            .SelectMany(record => record.Prefixes!.Select(prefix => new PrefixEntry(GetRequiredKey(record), prefix)))
            .OrderBy(static entry => entry.Subtag, Comparer)
            .ThenBy(static entry => entry.Prefix, Comparer)];
    }

    private static IReadOnlyList<ValueEntry> GetPrefixValueEntries(IReadOnlyList<RegistryRecord> records, string type)
    {
        return [.. records
            .Where(record => IsType(record, type) && record.Prefixes is not null)
            .SelectMany(record => record.Prefixes!.Select(prefix => new ValueEntry(GetRequiredKey(record), prefix)))
            .OrderBy(static entry => entry.Key, Comparer)
            .ThenBy(static entry => entry.Value, Comparer)];
    }

    private static IReadOnlyList<RangeEntry> GetRanges(IReadOnlyList<RegistryRecord> records, string type, bool deprecatedOnly)
    {
        return [.. records
            .Where(record => IsType(record, type) && IsRange(record) && (!deprecatedOnly || record.Deprecated is not null))
            .Select(record => ParseRange(GetRequiredKey(record)))
            .OrderBy(static entry => entry.Start, Comparer)
            .ThenBy(static entry => entry.End, Comparer)];
    }

    private static string GetRequiredKey(RegistryRecord record)
    {
        return record.Key!;
    }

    private static IReadOnlyList<ValueEntry> GetValueEntries(
        IReadOnlyList<RegistryRecord> records,
        string type,
        Func<RegistryRecord, string> valueSelector)
    {
        return [.. records
            .Where(record => IsType(record, type) && !IsRange(record))
            .Select(record => new ValueEntry(GetRequiredKey(record), valueSelector(record)))
            .Where(static entry => entry.Value is not null)
            .Select(static entry => new ValueEntry(entry.Key, entry.Value!))
            .OrderBy(static entry => entry.Key, Comparer)
            .ThenBy(static entry => entry.Value, Comparer)];
    }

    private static bool IsRange(RegistryRecord record)
    {
        return record.Key!.Contains("..");
    }

    private static bool IsType(RegistryRecord record, string type)
    {
        return string.Equals(record.Type, type, StringComparison.OrdinalIgnoreCase);
    }

    private static RangeEntry ParseRange(string value)
    {
        var separator = value.IndexOf("..", StringComparison.Ordinal);

        if (separator <= 0 || separator + 2 >= value.Length || value.IndexOf("..", separator + 2, StringComparison.Ordinal) >= 0)
        {
            throw new InvalidOperationException($"Invalid registry range '{value}'.");
        }

        return new RangeEntry(value.Substring(0, separator), value.Substring(separator + 2));
    }

    private static void ValidateRecords(IReadOnlyList<RegistryRecord> records)
    {
        var supportedTypes = new HashSet<string>(Comparer)
        {
            "language",
            "extlang",
            "script",
            "region",
            "variant",
            "grandfathered",
            "redundant"
        };

        foreach (var record in records)
        {
            if (record is null)
            {
                throw new InvalidOperationException("The registry snapshot contains a null record.");
            }

            if (record.Prefixes is not null && record.Prefixes.Any(string.IsNullOrWhiteSpace))
            {
                throw new InvalidOperationException($"The '{record.Type}' registry record '{record.Key}' contains an invalid prefix.");
            }

            if (string.IsNullOrWhiteSpace(record.Type) || !supportedTypes.Contains(record.Type))
            {
                throw new InvalidOperationException($"The registry snapshot contains an unsupported record type '{record.Type ?? "<null>"}'.");
            }

            if (string.IsNullOrWhiteSpace(record.Key))
            {
                throw new InvalidOperationException($"A '{record.Type}' registry record does not contain a subtag or tag.");
            }

            if ((IsType(record, "grandfathered") || IsType(record, "redundant")) && string.IsNullOrWhiteSpace(record.Tag))
            {
                throw new InvalidOperationException($"A '{record.Type}' registry record must use the 'tag' property.");
            }

            if (!(IsType(record, "grandfathered") || IsType(record, "redundant")) && string.IsNullOrWhiteSpace(record.Subtag))
            {
                throw new InvalidOperationException($"A '{record.Type}' registry record must use the 'subtag' property.");
            }

            if (IsRange(record))
            {
                _ = ParseRange(record.Key!);
            }
        }
    }

    private sealed class PrefixEntry
    {
        public PrefixEntry(string subtag, string prefix)
        {
            Subtag = subtag;
            Prefix = prefix;
        }

        public string Prefix { get; }
        public string Subtag { get; }
    }

    private sealed class RangeEntry
    {
        public RangeEntry(string start, string end)
        {
            Start = start;
            End = end;
        }

        public string End { get; }
        public string Start { get; }
    }

    private sealed class ValueEntry
    {
        public ValueEntry(string key, string value)
        {
            Key = key;
            Value = value;
        }

        public string Key { get; }
        public string Value { get; }
    }
}
